def seed_all():
    if Question.query.first() is None:
        for comp, skill, diff, text, opts, correct, expl in QUESTIONS:
            db.session.add(Question(
                competency=comp, skill=skill, difficulty=diff, text=text,
                options_json=json.dumps(opts), correct_index=correct, explanation=expl,
            ))
        db.session.commit()

    if User.query.first() is None:
        for username, fn, ln, role, pw, mob in DEMO_USERS:
            u = User(username=username, first_name=fn, last_name=ln,
                     email=f"{username}@merti.io", role=role, mobile=mob,
                     consent=True)
